def plan_to(page, needle, max_days=10):
    """Bladrer frem i dagsplanen, til en booking med teksten findes."""
    for _ in range(max_days):
        page.wait_for_selector(".plan, .notice")
        if page.locator(".plan__item", has_text=needle).count():
            return True
        page.click("button[aria-label='Næste dag']")
        page.wait_for_timeout(250)
    return False


